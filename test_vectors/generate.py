#!/usr/bin/env python3
"""Writes protocol_v1.json: fixed inputs and the bytes docs/protocol.md says they
encode or derive to. An independent implementation from the spec; the Kotlin
(android/.../protocol/VectorsTest) and Swift (ios/RunnerTests) tests must match it.

    python3 -I test_vectors/generate.py   # needs the `cryptography` package
"""
import hashlib
import hmac
import json
import os
import struct

from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat


def h(*parts):
    return hashlib.sha256(b"".join(parts)).digest()


def mac(key, *parts):
    return hmac.new(key, b"".join(parts), hashlib.sha256).digest()


def hkdf(ikm, salt, info, length):
    prk = mac(salt, ikm)
    out, block, counter = b"", b"", 1
    while len(out) < length:
        block = mac(prk, block, info, bytes([counter]))
        out += block
        counter += 1
    return out[:length]


def tlv(tag, value):
    return bytes([tag]) + struct.pack("<H", len(value)) + value


def hello(peer_id, nonce, name, platform, app_version, max_message_size, nonce_c=None):
    record = (bytes([1, 0x01]) + tlv(1, peer_id) + tlv(2, nonce) + tlv(3, name.encode())
              + tlv(4, bytes([platform])) + tlv(5, app_version.encode())
              + tlv(6, struct.pack("<I", max_message_size)))
    # HELLO_p echoes the nonce of the HELLO_c it answers.
    return record + tlv(7, nonce_c) if nonce_c else record


def envelope(type_, flags, msg_id, body):
    return bytes([type_, flags]) + struct.pack("<I", msg_id) + body


def data_envelope(msg_id, flags, path, reply_to, payload):
    body = bytes([len(path.encode())]) + path.encode()
    if flags & 0x02:
        body += struct.pack("<I", reply_to)
    return envelope(0x01, flags, msg_id, body + payload)


def private_key(byte):
    return ec.derive_private_key(int.from_bytes(bytes([byte]) * 32, "big"), ec.SECP256R1())


def public_bytes(key):
    return key.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)


def split(record, tid, size):
    if len(record) + 1 <= size:
        return [bytes([0xC0 | tid]) + record]
    frames = [bytes([0x80 | tid]) + struct.pack("<I", len(record)) + record[:size - 5]]
    offset = size - 5
    while offset < len(record):
        chunk = record[offset:offset + size - 1]
        offset += len(chunk)
        frames.append(bytes([(0x40 if offset == len(record) else 0) | tid]) + chunk)
    return frames


peer_c = bytes.fromhex("11111111111111111111111111111111")
peer_p = bytes.fromhex("0123456789abcdeffedcba9876543210")
hello_c = hello(peer_c, bytes(range(16)), "재홍의 Z Fold5", 1, "1.0.0", 65536)
hello_p = hello(peer_p, bytes(range(16, 32)), "RouddySE", 2, "1.0.0", 65536, nonce_c=bytes(range(16)))
t_hello = h(hello_c, hello_p)

key_p, key_c = private_key(0x22), private_key(0x33)
pk_p, pk_c = public_bytes(key_p), public_bytes(key_c)
shared = key_c.exchange(ec.ECDH(), key_p.public_key())
assert shared == key_p.exchange(ec.ECDH(), key_c.public_key())
t_pair = h(t_hello, pk_p, pk_c)
k = hkdf(shared, t_pair, b"rbc-pair-key-v1", 32)
code = "%06d" % (struct.unpack("<I", h(b"rbc-code-v1", t_pair)[:4])[0] % 1_000_000)
session_cp = mac(k, b"rbc-session-v1", peer_c, peer_p, t_hello)
session_pc = mac(k, b"rbc-session-v1", peer_p, peer_c, t_hello)

sealed_envelope = data_envelope(41, 0x01, "/control/media", 0, bytes([1]))
sealed_header = bytes([1, 0x10]) + struct.pack("<I", 7)
nonce = struct.pack("<I", 7) + bytes(8)
sealed_record = sealed_header + AESGCM(session_cp).encrypt(nonce, sealed_envelope, sealed_header)

caps_body = (tlv(1, b"/control/media")
             + tlv(2, bytes([len(b"com.example.app")]) + b"com.example.app" + bytes.fromhex("ab" * 32)))
frame_record = bytes(range(50))

vectors = {
    "comment": "Generated by generate.py from docs/protocol.md. All byte strings are hex.",
    "handshake": {
        "peerIdC": peer_c.hex(),
        "peerIdP": peer_p.hex(),
        "helloC": {"nonce": bytes(range(16)).hex(), "name": "재홍의 Z Fold5", "platform": 1,
                   "appVersion": "1.0.0", "maxMessageSize": 65536, "bytes": hello_c.hex()},
        "helloP": {"nonce": bytes(range(16, 32)).hex(), "name": "RouddySE", "platform": 2,
                   "appVersion": "1.0.0", "maxMessageSize": 65536, "nonceC": bytes(range(16)).hex(),
                   "bytes": hello_p.hex()},
        "tHello": t_hello.hex(),
        "privateKeyP": (bytes([0x22]) * 32).hex(),
        "privateKeyC": (bytes([0x33]) * 32).hex(),
        "publicKeyP": pk_p.hex(),
        "publicKeyC": pk_c.hex(),
        "commit": h(b"rbc-commit-v1", pk_p).hex(),
        "sharedSecret": shared.hex(),
        "tPair": t_pair.hex(),
        "pairKey": k.hex(),
        "code": code,
        "confirmMacC": mac(k, b"rbc-confirm-v1", peer_c, t_pair).hex(),
        "confirmMacP": mac(k, b"rbc-confirm-v1", peer_p, t_pair).hex(),
        "authMacC": mac(k, b"rbc-auth-v1", peer_c, t_hello).hex(),
        "authMacP": mac(k, b"rbc-auth-v1", peer_p, t_hello).hex(),
        "sessionKeyCtoP": session_cp.hex(),
        "sessionKeyPtoC": session_pc.hex(),
    },
    "sealed": {
        "key": session_cp.hex(),
        "counter": 7,
        "envelope": sealed_envelope.hex(),
        "record": sealed_record.hex(),
    },
    "envelopes": {
        "dataRequest": sealed_envelope.hex(),
        "dataReply": data_envelope(7, 0x02, "/control/media", 41, bytes([0, 1])).hex(),
        "ack": envelope(0x02, 0, 0, struct.pack("<I", 41) + bytes([1])).hex(),
        "caps": envelope(0x03, 0, 9, caps_body).hex(),
        "unpair": envelope(0x04, 0x01, 10, b"").hex(),
    },
    "records": {
        "auth": (bytes([1, 0x02]) + bytes([0xAA]) * 32).hex(),
        "pairRequest": bytes([1, 0x03]).hex(),
        "reject": bytes([1, 0x07, 3]).hex(),
    },
    "frames": {
        "record": frame_record.hex(),
        "tid": 5,
        "maxFrameSize": 20,
        "frames": [f.hex() for f in split(frame_record, 5, 20)],
    },
}

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "protocol_v1.json")
with open(path, "w", encoding="utf-8") as out:
    json.dump(vectors, out, ensure_ascii=False, indent=2)
    out.write("\n")
print("wrote", path)
